const TWELVE_STAGE_START: number[] = [
  11, // 갑(목양) → 해(11)에서 장생
  6,  // 을(목음) → 오(6)에서 사(역순 장생)
  2,  // 병(화양) → 인(2)에서 장생
  9,  // 정(화음) → 유(9)에서 사
  2,  // 무(토양) → 인(2)에서 장생
  9,  // 기(토음) → 유(9)에서 사
  5,  // 경(금양) → 사(5)에서 장생
  0,  // 신(금음) → 자(0)에서 사
  8,  // 임(수양) → 신(8)에서 장생
  3,  // 계(수음) → 묘(3)에서 사
];

export function getTwelveStage(stemIndex: number, branchIndex: number): TwelveStage {
  const start = TWELVE_STAGE_START[stemIndex];
  const offset = (branchIndex - start + 12) % 12;
  return TWELVE_STAGE_TABLE[stemIndex][offset];
}

