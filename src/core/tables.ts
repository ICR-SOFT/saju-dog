// ===== 시간 → 지지 매핑 (시주) =====
// 자시: 23:00~00:59, 축시: 01:00~02:59, ...

export function getHourBranchIndex(hour: number): number {
  // 23시~00시 → 자(0), 1~2시 → 축(1), ...
  if (hour === 23) return 0;
  return Math.floor((hour + 1) / 2);
}

// ===== 십신 (Ten Gods) 계산 =====
// 일간 기준으로 다른 천간의 십신을 구한다
// 오행 관계: 비견/겁재(같은), 식신/상관(내가 생), 편재/정재(내가 극),
//           편관/정관(나를 극), 편인/정인(나를 생)

const OHAENG_INDEX: Record<Ohaeng, number> = { '목': 0, '화': 1, '토': 2, '금': 3, '수': 4 };

// 생극 관계 매핑: [같은, 내가 생, 내가 극, 나를 극, 나를 생]
const RELATION_MAP: [Ohaeng, Ohaeng, Ohaeng, Ohaeng, Ohaeng][] = [
  ['목', '화', '토', '금', '수'], // 목 기준
  ['화', '토', '금', '수', '목'], // 화 기준
  ['토', '금', '수', '목', '화'], // 토 기준
  ['금', '수', '목', '화', '토'], // 금 기준
  ['수', '목', '화', '토', '금'], // 수 기준
];

export function getSipsin(dayStemOhaeng: Ohaeng, dayStemYinYang: YinYang, targetOhaeng: Ohaeng, targetYinYang: YinYang): string {
  const relations = RELATION_MAP[OHAENG_INDEX[dayStemOhaeng]];
  const relationIndex = relations.indexOf(targetOhaeng);

  const sameYinYang = dayStemYinYang === targetYinYang;

  const SIPSIN_PAIRS = [
    ['비견', '겁재'],   // 같은 오행
    ['식신', '상관'],   // 내가 생
    ['편재', '정재'],   // 내가 극
    ['편관', '정관'],   // 나를 극
    ['편인', '정인'],   // 나를 생
  ];

  return SIPSIN_PAIRS[relationIndex][sameYinYang ? 0 : 1];
}

